def read_summary(path: Path) -> dict:
    with open(path, encoding="utf-8-sig", newline="") as f:
        raw = {r["metric"].strip(): float(r["mean"])
               for r in csv.DictReader(f) if r.get("mean")}
    # Keep the original labels as well (E4 uses a different naming scheme).
    out = dict(raw)
    for key, names in ALIASES.items():
        for n in names:
            if n in raw:
                out[key] = raw[n]
                break
    return out


def summary_of(name: str, sub: str = "eval") -> dict:
    return read_summary(RUNS / name / sub / "summary.csv")


def n_images(name: str, sub: str = "eval") -> int:
    p = RUNS / name / sub / "per_image.csv"
    with open(p, encoding="utf-8-sig", newline="") as f:
        return sum(1 for _ in csv.reader(f)) - 1


def manifest_rows(name: str) -> int:
    with open(MAN / f"{name}.csv", encoding="utf-8-sig", newline="") as f:
        return sum(1 for _ in csv.DictReader(f))


def fmt(v, digits: int = 3) -> str:
    if v is None:
        return "—"
    return f"{v:.{digits}f}"


# ------------------------------------------------------------------ tables
def _md_clean(s: str) -> str:
    for a, b in [("$\\times$", "x"), ("$\\leq$", "<="), ("$\\lambda$", "\u03bb"),
                 ("\\textit{", ""), ("\\multicolumn{9}{l}{", ""), ("\\ref{", "ref:")]:
        s = s.replace(a, b)
    return s.replace("}", "").replace("\\", "")


def write_table(stem: str, caption: str, label: str, header: list[str],
                rows: list[list[str]], tex_note: str = "", md_note: str = ""):
    """Write a booktabs LaTeX table fragment and a Markdown mirror."""
    colspec = "l" + "c" * (len(header) - 1)
    t = ["% AUTO-GENERATED by tools/build_manuscript_tables.py -- DO NOT EDIT",
         "\\begin{table}[htbp]", "\\centering",
         f"\\caption{{{caption}}}", f"\\label{{{label}}}",
         "\\resizebox{\\linewidth}{!}{%",
         f"\\begin{{tabular}}{{{colspec}}}", "\\toprule",
         " & ".join(header) + " \\\\", "\\midrule"]
    for r in rows:
        t.append(" & ".join(str(x) for x in r) + " \\\\")
    t += ["\\bottomrule", "\\end{tabular}", "}"]
    if tex_note:
        t.append(f"\\par\\smallskip\\footnotesize {tex_note}")
    t += ["\\end{table}", ""]
    (OUT / f"{stem}.tex").write_text("\n".join(t), encoding="utf-8")

    m = [f"**{_md_clean(caption)}**", "",
         "| " + " | ".join(_md_clean(h) for h in header) + " |",
         "|" + "|".join(["---"] * len(header)) + "|"]
    for r in rows:
        if len(r) == 1:
            cell = _md_clean(str(r[0]))
            m.append("| **" + cell + "** |" + " |".join([""] * (len(header) - 1)) + " |")
        else:
            m.append("| " + " | ".join(_md_clean(str(x)) for x in r) + " |")
    if md_note:
        m += ["", md_note]
    m.append("")
    (OUT / f"{stem}.md").write_text("\n".join(m), encoding="utf-8")


